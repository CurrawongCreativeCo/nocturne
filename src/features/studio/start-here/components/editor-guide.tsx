import { LaunchIcon } from '@sanity/icons/Launch'
import { Button, Card, Flex, Heading, Stack, Text } from '@sanity/ui'
import type { ReactNode } from 'react'

import { Markdown } from './markdown'
import {
  videoFor,
  type EditorGuide as EditorGuideData,
  type GuideField,
  type GuideSection,
} from '../utils/editor-guide'

const LIST_STYLE = { listStyle: 'none', margin: 0, padding: 0 } as const
const SUMMARY_STYLE = { cursor: 'pointer', padding: '0.75rem 1rem' } as const

/** A collapsed card that opens on Enter or Space; `details` gives that, and a focus ring, for free. */
function Disclosure({
  title,
  summary,
  children,
}: {
  title: string
  summary?: string
  children: ReactNode
}) {
  return (
    <Card as="li" radius={2} border>
      <details>
        <summary style={SUMMARY_STYLE}>
          <Text as="span" size={1} weight="semibold">
            {title}
          </Text>
          {summary && (
            <Text as="span" size={1} muted>
              {' '}
              · {summary}
            </Text>
          )}
        </summary>
        <div style={{ padding: '0.25rem 1rem 1rem' }}>{children}</div>
      </details>
    </Card>
  )
}

/** The guides and the sections for this site, as generated by scripts/build-editor-guide.mjs. */
export function EditorGuide({
  guide,
  videos,
}: {
  guide: EditorGuideData
  videos: Readonly<Record<string, string>> | undefined
}) {
  return (
    <Stack gap={6}>
      {guide.guides.length > 0 && (
        <Stack as="section" gap={4} aria-labelledby="editor-guide-tasks">
          <Heading as="h3" size={1} id="editor-guide-tasks">
            How to do common jobs
          </Heading>
          <Stack as="ul" gap={2} style={LIST_STYLE}>
            {guide.guides.map((entry) => {
              const video = videoFor(entry.id, videos)
              return (
                <Disclosure key={entry.id} title={entry.title} summary={entry.summary}>
                  <Stack gap={4}>
                    <Markdown source={entry.body} />
                    {video && (
                      <Flex>
                        <Button
                          as="a"
                          href={video}
                          target="_blank"
                          rel="noopener noreferrer"
                          text="Watch the video (new tab)"
                          icon={LaunchIcon}
                          mode="ghost"
                          fontSize={1}
                        />
                      </Flex>
                    )}
                  </Stack>
                </Disclosure>
              )
            })}
          </Stack>
        </Stack>
      )}

      {guide.sections.length > 0 && (
        <Stack as="section" gap={4} aria-labelledby="editor-guide-sections">
          <Heading as="h3" size={1} id="editor-guide-sections">
            Sections you can add to a page
          </Heading>
          <Text muted size={1}>
            Open a page, choose <strong>Add item</strong> and pick one of these. Here is what each
            one asks for.
          </Text>
          <Stack as="ul" gap={2} style={LIST_STYLE}>
            {guide.sections.map((section) => (
              <Disclosure key={section.name} title={section.title}>
                <SectionDetails section={section} />
              </Disclosure>
            ))}
          </Stack>
        </Stack>
      )}
    </Stack>
  )
}

function SectionDetails({ section }: { section: GuideSection }) {
  return (
    <Stack gap={4}>
      {section.description && <Text size={1}>{section.description}</Text>}
      <FieldList fields={section.fields} />
    </Stack>
  )
}

function FieldList({ fields }: { fields: GuideField[] }) {
  return (
    <Stack as="ul" gap={3} style={LIST_STYLE}>
      {fields.map((field) => (
        <li key={field.name}>
          <Stack gap={2}>
            <Text size={1}>
              <strong>{field.title}</strong> · {field.kind}
              {field.required ? ' · required' : ''}
            </Text>
            {field.description && (
              <Text size={1} muted>
                {field.description}
              </Text>
            )}
            {field.imageSize && (
              <Text size={1} muted>
                Recommended picture size: {field.imageSize}
              </Text>
            )}
            {field.length && (
              <Text size={1} muted>
                {field.length}.
              </Text>
            )}
            {field.choices && (
              <Text size={1} muted>
                Choose from: {field.choices.join(', ')}.
              </Text>
            )}
            {field.items && (
              <div style={{ paddingLeft: '1rem' }}>
                <FieldList fields={field.items} />
              </div>
            )}
          </Stack>
        </li>
      ))}
    </Stack>
  )
}
