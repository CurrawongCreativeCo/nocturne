/**
 * SEO launch checks over the pages the CLI fetched. A page is `{ url, status, html }` (final URL
 * and body after redirects). Sitemap and robots.txt parsing is pure too.
 */
import { countH1, decodeEntities, getCanonical, getMeta, getTitle, isNoindex } from './html.mjs'
import { fail, listSome, pass, warn } from './result.mjs'

const area = 'SEO'

export const MAX_SITEMAP_URLS = 200

/** Hosts that mean "not the real site". */
export function isNonProductionHost(hostname) {
  const host = hostname.toLowerCase()
  return (
    host === 'localhost' ||
    host.endsWith('.localhost') ||
    host === '0.0.0.0' ||
    host.startsWith('127.') ||
    host.endsWith('.vercel.app') ||
    host.endsWith('.local')
  )
}

const path = (url) => {
  const parsed = new URL(url)
  return `${parsed.pathname}${parsed.search}` || '/'
}

/** Canonical links must be absolute, on the production domain and over HTTPS. */
export function checkCanonicals({ pages, origin }) {
  const id = 'seo-canonical'
  const title = 'Canonical URLs use the production domain'
  const site = new URL(origin)
  const wrongHost = []
  const missing = []
  for (const page of pages) {
    const href = getCanonical(page.html)
    if (!href) {
      missing.push(path(page.url))
      continue
    }
    let canonical
    try {
      canonical = new URL(href)
    } catch {
      wrongHost.push(`${path(page.url)} (${href} isn't an absolute URL)`)
      continue
    }
    if (isNonProductionHost(canonical.hostname) && !isNonProductionHost(site.hostname)) {
      wrongHost.push(`${path(page.url)} → ${canonical.origin}`)
    } else if (canonical.origin !== site.origin) {
      wrongHost.push(`${path(page.url)} → ${canonical.origin}`)
    }
  }
  if (wrongHost.length > 0) {
    return [
      fail(
        area,
        id,
        title,
        `${wrongHost.length} page${wrongHost.length === 1 ? ' points' : 's point'} elsewhere: ${listSome(wrongHost, 3)}.`,
        `Set NEXT_PUBLIC_SITE_URL to ${site.origin} in Vercel (Production) and redeploy.`,
      ),
    ]
  }
  if (missing.length > 0) {
    return [
      warn(
        area,
        id,
        title,
        `No canonical link on ${listSome(missing, 3)}.`,
        'Pages should declare their canonical URL in generateMetadata.',
      ),
    ]
  }
  return [pass(area, id, title, `${pages.length} page${pages.length === 1 ? '' : 's'} checked.`)]
}

/** Groups, per user-agent, of `{ allow, disallow }` path rules, plus every Sitemap line. */
export function parseRobots(text) {
  const groups = []
  const sitemaps = []
  let current = null
  let lastWasAgent = false
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.replace(/#.*$/, '').trim()
    const match = /^([a-z-]+)\s*:\s*(.*)$/i.exec(line)
    if (!match) continue
    const key = match[1].toLowerCase()
    const value = match[2].trim()
    if (key === 'user-agent') {
      if (!current || !lastWasAgent) {
        current = { agents: [], allow: [], disallow: [] }
        groups.push(current)
      }
      current.agents.push(value.toLowerCase())
      lastWasAgent = true
      continue
    }
    lastWasAgent = false
    if (key === 'sitemap') sitemaps.push(value)
    else if (current && key === 'allow') current.allow.push(value)
    else if (current && key === 'disallow') current.disallow.push(value)
  }
  return { groups, sitemaps }
}

export function checkRobots({ status, text, origin }) {
  if (status !== 200) {
    return [
      fail(
        area,
        'seo-robots',
        'robots.txt allows crawling and lists the sitemap',
        `${origin}/robots.txt returned HTTP ${status}.`,
        'robots.txt is generated by src/app/robots.ts; check the deployment logs.',
      ),
    ]
  }
  const { groups, sitemaps } = parseRobots(text)
  const everyone = groups.filter((group) => group.agents.includes('*'))
  const blocksAll = everyone.some(
    (group) => group.disallow.includes('/') && !group.allow.some((rule) => rule === '/'),
  )
  const results = []
  if (blocksAll) {
    results.push(
      fail(
        area,
        'seo-robots-crawling',
        'robots.txt allows crawling',
        'The "*" group has "Disallow: /", so search engines are told to stay away.',
        'Remove the site-wide Disallow. src/app/robots.ts allows everything except Studio and /api/.',
      ),
    )
  } else {
    results.push(pass(area, 'seo-robots-crawling', 'robots.txt allows crawling'))
  }
  if (sitemaps.length === 0) {
    results.push(
      fail(
        area,
        'seo-robots-sitemap',
        'robots.txt lists the sitemap',
        'There is no "Sitemap:" line.',
        'src/app/robots.ts adds it from the site URL; check NEXT_PUBLIC_SITE_URL is set.',
      ),
    )
  } else {
    const off = sitemaps.filter((entry) => {
      try {
        return new URL(entry).origin !== new URL(origin).origin
      } catch {
        return true
      }
    })
    results.push(
      off.length > 0
        ? fail(
            area,
            'seo-robots-sitemap',
            'robots.txt lists the sitemap',
            `Sitemap line${off.length === 1 ? '' : 's'} on another origin: ${listSome(off, 3)}.`,
            `Set NEXT_PUBLIC_SITE_URL to ${origin} in Vercel (Production) and redeploy.`,
          )
        : pass(area, 'seo-robots-sitemap', 'robots.txt lists the sitemap', listSome(sitemaps, 3)),
    )
  }
  return results
}

/** `<loc>` entries of a urlset, or of a sitemapindex (`type: 'index'`). */
export function parseSitemapXml(xml) {
  const type = /<sitemapindex\b/i.test(xml) ? 'index' : 'urlset'
  const locs = [...xml.matchAll(/<loc>\s*([\s\S]*?)\s*<\/loc>/gi)].map((m) =>
    decodeEntities(m[1].replace(/^<!\[CDATA\[|\]\]>$/g, '')).trim(),
  )
  return { type, locs }
}

/**
 * Every page URL the sitemaps list, up to `cap`. `get(url)` returns `{ status, text }`; a sitemap
 * index is followed one level. `problems` names sitemap files that couldn't be read.
 */
export async function loadSitemapUrls({ sitemapUrls, get, cap = MAX_SITEMAP_URLS }) {
  const urls = []
  const problems = []
  const unique = new Set()
  const queue = [...sitemapUrls]
  const seen = new Set()
  while (queue.length > 0) {
    const sitemapUrl = queue.shift()
    if (seen.has(sitemapUrl)) continue
    seen.add(sitemapUrl)
    const response = await get(sitemapUrl)
    if (response.status !== 200 || !response.text) {
      problems.push(`${sitemapUrl} (${response.error ?? `HTTP ${response.status}`})`)
      continue
    }
    const { type, locs } = parseSitemapXml(response.text)
    if (type === 'index') {
      if (seen.size < 50) queue.push(...locs)
      continue
    }
    for (const loc of locs) {
      if (unique.has(loc)) continue
      unique.add(loc)
      if (urls.length < cap) urls.push(loc)
    }
  }
  const total = unique.size
  return { urls, total, capped: total > urls.length, problems }
}

/** Sitemap entries must be on the site's own origin; others can't be launch-checked as the site. */
export function checkSitemapEntries({ urls, total, capped, problems, origin }) {
  const id = 'seo-sitemap'
  const title = 'Sitemap is readable and lists production URLs'
  if (problems.length > 0 && urls.length === 0) {
    return [
      fail(
        area,
        id,
        title,
        `Couldn't read ${listSome(problems, 3)}.`,
        'The sitemap is generated by src/app/sitemap.ts; check the deployment logs.',
      ),
    ]
  }
  if (urls.length === 0) {
    return [
      fail(
        area,
        id,
        title,
        'The sitemap lists no URLs.',
        'Publish at least the home page in Studio.',
      ),
    ]
  }
  const site = new URL(origin)
  const offSite = urls.filter((url) => new URL(url).origin !== site.origin)
  if (offSite.length > 0) {
    return [
      fail(
        area,
        id,
        title,
        `${offSite.length} URL${offSite.length === 1 ? '' : 's'} on another origin: ${listSome(offSite, 3)}.`,
        `Set NEXT_PUBLIC_SITE_URL to ${site.origin} in Vercel (Production) and redeploy.`,
      ),
    ]
  }
  const notes = []
  if (capped) notes.push(`Only the first ${urls.length} of ${total} URLs are checked.`)
  if (problems.length > 0) notes.push(`Couldn't read ${listSome(problems, 3)}.`)
  const message = `${total} URL${total === 1 ? '' : 's'}. ${notes.join(' ')}`.trim()
  return problems.length > 0
    ? [warn(area, id, title, message, 'Fix the unreadable sitemap files listed above.')]
    : [pass(area, id, title, message)]
}

/** `statuses` is an array of `{ url, status, redirectedTo?, error? }` for each sitemap URL. */
export function checkSitemapStatuses({ statuses }) {
  const id = 'seo-sitemap-status'
  const title = 'Every sitemap URL returns 200'
  const bad = statuses.filter((entry) => entry.status !== 200)
  if (bad.length === 0) {
    return [
      pass(area, id, title, `${statuses.length} URL${statuses.length === 1 ? '' : 's'} checked.`),
    ]
  }
  const lines = bad.map((entry) =>
    entry.error
      ? `${path(entry.url)} (${entry.error})`
      : `${path(entry.url)} (${entry.status}${entry.redirectedTo ? ` → ${entry.redirectedTo}` : ''})`,
  )
  return [
    fail(
      area,
      id,
      title,
      `${bad.length} of ${statuses.length} failed: ${listSome(lines, 4)}.`,
      'Sitemaps should list final, working URLs. Unpublish or fix the page in Studio, or add a redirect and remove the old entry.',
    ),
  ]
}

function duplicates(entries) {
  const byValue = new Map()
  for (const { url, value } of entries) {
    const key = value.toLowerCase()
    byValue.set(key, [...(byValue.get(key) ?? []), url])
  }
  return [...byValue.entries()].filter(([, urls]) => urls.length > 1)
}

export function checkUniqueMetadata({ pages }) {
  const results = []
  const titles = pages.map((page) => ({ url: page.url, value: getTitle(page.html) }))
  const noTitle = titles.filter((entry) => !entry.value)
  const dupTitles = duplicates(titles.filter((entry) => entry.value))
  const titleTitle = 'Page titles are unique'
  if (noTitle.length > 0 || dupTitles.length > 0) {
    const parts = []
    if (noTitle.length > 0)
      parts.push(
        `No title on ${listSome(
          noTitle.map((e) => path(e.url)),
          3,
        )}`,
      )
    for (const [value, urls] of dupTitles.slice(0, 2)) {
      parts.push(`"${value}" is used on ${listSome(urls.map(path), 3)}`)
    }
    results.push(
      fail(
        area,
        'seo-titles',
        titleTitle,
        `${parts.join('; ')}.`,
        'Give each page its own SEO title in Studio (page → SEO).',
      ),
    )
  } else {
    results.push(pass(area, 'seo-titles', titleTitle))
  }

  const descriptions = pages.map((page) => ({
    url: page.url,
    value: getMeta(page.html, 'description'),
  }))
  const noDescription = descriptions.filter((entry) => !entry.value)
  const dupDescriptions = duplicates(descriptions.filter((entry) => entry.value))
  const descriptionTitle = 'Meta descriptions are unique'
  if (dupDescriptions.length > 0) {
    const [value, urls] = dupDescriptions[0]
    results.push(
      fail(
        area,
        'seo-descriptions',
        descriptionTitle,
        `"${value.slice(0, 60)}${value.length > 60 ? '…' : ''}" is used on ${listSome(urls.map(path), 3)}${dupDescriptions.length > 1 ? ` (and ${dupDescriptions.length - 1} more repeated)` : ''}.`,
        'Write a different meta description for each page in Studio (page → SEO).',
      ),
    )
  } else if (noDescription.length > 0) {
    results.push(
      warn(
        area,
        'seo-descriptions',
        descriptionTitle,
        `No meta description on ${listSome(
          noDescription.map((e) => path(e.url)),
          4,
        )}.`,
        'Add one in Studio (page → SEO); search engines otherwise pick their own snippet.',
      ),
    )
  } else {
    results.push(pass(area, 'seo-descriptions', descriptionTitle))
  }
  return results
}

export function checkSingleH1({ pages }) {
  const id = 'seo-h1'
  const title = 'Each page has exactly one h1'
  const bad = pages
    .map((page) => ({ url: page.url, count: countH1(page.html) }))
    .filter((entry) => entry.count !== 1)
  if (bad.length === 0) return [pass(area, id, title)]
  return [
    fail(
      area,
      id,
      title,
      `${listSome(
        bad.map((e) => `${path(e.url)} has ${e.count}`),
        4,
      )}.`,
      'Use one hero or heading section as the page title; later sections render as h2.',
    ),
  ]
}

/** Pages whose robots meta says noindex: a staging leftover on the home page blocks the whole site. */
export function checkIndexable({ pages, homeUrl, headerValues = {} }) {
  const id = 'seo-noindex'
  const title = 'Pages can be indexed'
  const hidden = pages.filter(
    (page) => isNoindex(getMeta(page.html, 'robots')) || isNoindex(headerValues[page.url] ?? ''),
  )
  if (hidden.length === 0) return [pass(area, id, title)]
  const home = hidden.some((page) => page.url === homeUrl)
  const names = listSome(
    hidden.map((page) => path(page.url)),
    4,
  )
  return home
    ? [
        fail(
          area,
          id,
          title,
          `The home page is marked noindex (${names}).`,
          'Clear "Hide from search engines" on the page in Studio (page → SEO), and check no X-Robots-Tag header is set.',
        ),
      ]
    : [
        warn(
          area,
          id,
          title,
          `Marked noindex: ${names}.`,
          'Fine if they are meant to be hidden; otherwise clear "Hide from search engines" in Studio.',
        ),
      ]
}

/** og:image URLs per page, to fetch once each. */
export function collectOgImages(pages) {
  const images = new Map()
  const missing = []
  for (const page of pages) {
    const value = getMeta(page.html, 'og:image')
    if (!value) {
      missing.push(page.url)
      continue
    }
    let url
    try {
      url = new URL(value, page.url).toString()
    } catch {
      continue
    }
    images.set(url, [...(images.get(url) ?? []), page.url])
  }
  return { images, missing }
}

/** `fetched` is an array of `{ url, status, contentType, error? }` for the images in `collectOgImages`. */
export function checkOgImages({ fetched, missing, total }) {
  const id = 'seo-og-image'
  const title = 'og:image returns an image'
  const broken = fetched.filter(
    (entry) => entry.status !== 200 || !/^image\//i.test(entry.contentType ?? ''),
  )
  if (broken.length > 0) {
    const lines = broken.map((entry) =>
      entry.error
        ? `${entry.url} (${entry.error})`
        : `${entry.url} (${entry.status}, ${entry.contentType || 'no content type'})`,
    )
    return [
      fail(
        area,
        id,
        title,
        `${listSome(lines, 3)}.`,
        "Social previews break. The default share image is /api/og; check the URL isn't on localhost and the route works in production.",
      ),
    ]
  }
  if (fetched.length === 0) {
    return [
      fail(
        area,
        id,
        title,
        'No page sets an og:image.',
        'Add a default share image in Studio (Site settings → SEO).',
      ),
    ]
  }
  if (missing.length > 0) {
    return [
      warn(
        area,
        id,
        title,
        `${fetched.length} image${fetched.length === 1 ? '' : 's'} fine; no og:image on ${listSome(missing.map(path), 3)} of ${total} pages.`,
        'Add a default share image in Studio (Site settings → SEO).',
      ),
    ]
  }
  return [
    pass(area, id, title, `${fetched.length} image${fetched.length === 1 ? '' : 's'} checked.`),
  ]
}
