/**
 * Pure helpers for `npm run config:docs`: `.env.example` and the README's settings table, both
 * written from the feature registries (src/app/feature-registry.ts). No file access here, so the
 * tests can feed them a registry and read the text back. A registry holds names and words, never
 * values, so nothing here can print one.
 */

export const README_START = '<!-- config:settings:start -->'
export const README_END = '<!-- config:settings:end -->'

const WIDTH = 100

const WHERE = {
  vercel: 'Vercel',
  github: 'GitHub',
  sanity: 'Sanity',
  'site.profile.ts': 'site.profile.ts',
  local: '.env.local',
}

const TARGET = { production: 'Production', preview: 'Preview', development: 'Development' }

/** Words wrapped to `WIDTH` columns, each line starting with `prefix`. */
export function wrap(text, prefix = '# ') {
  const lines = []
  let line = ''
  for (const word of text.split(/\s+/).filter(Boolean)) {
    if (line && prefix.length + line.length + 1 + word.length > WIDTH) {
      lines.push(prefix + line)
      line = word
    } else {
      line = line ? `${line} ${word}` : word
    }
  }
  if (line) lines.push(prefix + line)
  return lines
}

/** A setting an environment file can hold: Vercel or local, and not hidden from the example. */
function isEnvSetting(setting) {
  return (setting.where === 'vercel' || setting.where === 'local') && setting.envExample !== false
}

/** Hand-written text in the registry never ends a sentence with a stop; add one so the file reads well. */
function sentence(text) {
  const trimmed = text.trim()
  return /[.!?:)"]$/.test(trimmed) ? trimmed : `${trimmed}.`
}

/** The text of `.env.example`. */
export function buildEnvExample(registry) {
  const lines = [
    '# Generated by `npm run config:docs` from the feature registries (src/app/feature-registry.ts).',
    '# Do not edit it by hand: change the registry entry and regenerate. CI fails when it is stale.',
    '# Copy it to .env.local. These are examples and empty slots, never real values. Every setting,',
    '# where it goes and what it is for is in the README: "Configuration" → "Every setting".',
  ]
  const seen = new Map()

  for (const feature of registry) {
    const own = []
    const shared = []
    for (const setting of feature.settings) {
      if (!isEnvSetting(setting) || setting.deprecated) continue
      if (seen.has(setting.name)) shared.push(setting.name)
      else {
        seen.set(setting.name, feature.title)
        own.push(setting)
      }
    }
    if (own.length === 0) continue

    lines.push('', ...wrap(`${feature.title}: ${sentence(feature.summary)}`))
    if (feature.tier === 'optional') lines.push('# Optional. An empty line means the default.')
    lines.push(`# See ${feature.docs}.`)
    if (shared.length > 0) {
      lines.push(...wrap(`Also uses ${shared.join(', ')}, set above.`))
    }

    for (const setting of own) {
      const detail = [setting.purpose && sentence(setting.purpose)]
      if (setting.default) detail.push(`Default: ${sentence(setting.default)}`)
      if (setting.source) detail.push(`Get it from: ${sentence(setting.source)}`)
      lines.push(...wrap(detail.filter(Boolean).join(' ')))
      const placeholder = setting.envExample?.placeholder ?? ''
      const line = `${setting.name}="${placeholder}"`
      lines.push(setting.envExample?.commented ? `# ${line}` : line)
    }
  }
  return `${lines.join('\n')}\n`
}

/** Table cells can't hold a pipe or raw angle brackets (a `<site>` would vanish as HTML). */
function cell(text) {
  return String(text)
    .replace(/\|/g, '\\|')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/\s+/g, ' ')
    .trim()
}

function whereLabel(setting) {
  if (setting.kind === 'github-var') return 'GitHub variable'
  if (setting.kind === 'github-secret') return 'GitHub secret'
  return WHERE[setting.where] ?? setting.where
}

function neededLabel(setting) {
  if (setting.deprecated) return 'Deprecated'
  if (setting.planned) return 'Not used yet'
  if (typeof setting.required === 'object') return `Required with \`${setting.required.when}\``
  return setting.required ? 'Required' : 'Optional'
}

function environments(setting) {
  if (setting.where !== 'vercel') return '—'
  return (setting.targets ?? []).map((target) => TARGET[target]).join(', ') || '—'
}

function readLabel(setting) {
  if (setting.where !== 'vercel') return '—'
  return setting.buildTime ? 'Build' : 'Run'
}

function describeSetting(setting) {
  const parts = []
  if (setting.purpose) parts.push(sentence(setting.purpose))
  if (setting.default) parts.push(`Default: ${sentence(setting.default)}`)
  if (setting.source) parts.push(`Get it from: ${sentence(setting.source)}`)
  if (setting.deprecated) {
    parts.push(
      `**Deprecated:** replaced by ${setting.deprecated.replacedBy}. ${sentence(setting.deprecated.migration)}`,
    )
  }
  return cell(parts.join(' '))
}

/** One row per name and place; a setting several features use lists them all. */
export function collectRows(registry) {
  const rows = new Map()
  for (const feature of registry) {
    for (const setting of feature.settings) {
      const key = `${setting.name}\u0000${whereLabel(setting)}`
      const row = rows.get(key)
      if (row) row.features.push(feature.title)
      else rows.set(key, { setting, features: [feature.title] })
    }
  }
  return [...rows.values()]
}

/** The README block between the markers, markers included (Prettier lays the table out afterwards). */
export function buildSettingsBlock(registry) {
  const header = '| Setting | Feature | Where | Environments | Read | Needed | What it is for |'
  const divider = '| --- | --- | --- | --- | --- | --- | --- |'
  const body = collectRows(registry).map(({ setting, features }) =>
    [
      `\`${setting.name}\``,
      cell(features.join(', ')),
      whereLabel(setting),
      environments(setting),
      readLabel(setting),
      neededLabel(setting),
      describeSetting(setting),
    ]
      .join(' | ')
      .replace(/^/, '| ')
      .replace(/$/, ' |'),
  )

  return [
    README_START,
    '',
    '_Generated by `npm run config:docs` from the feature registries: change the registry entry, not this table. CI fails when it is stale._',
    '',
    '**Environments** are the Vercel environments to add a variable to. **Read** says when Vercel uses it: _Build_ values are built into the pages, so changing one needs a redeploy; _Run_ values are read per deployment, which also needs a redeploy on Vercel. **Needed** means needed _for that feature_: a missing setting for a feature you do not use is not a problem, and only the two Sanity core values can stop a build.',
    '',
    header,
    divider,
    ...body,
    '',
    README_END,
  ].join('\n')
}

/** `readme` with the generated block replaced, or null when the markers are missing or out of order. */
export function spliceBlock(readme, block) {
  const start = readme.indexOf(README_START)
  const end = readme.indexOf(README_END)
  if (start === -1 || end === -1 || end < start) return null
  return readme.slice(0, start) + block + readme.slice(end + README_END.length)
}
