/**
 * The design capability baseline (task 275; README, "Design capability contract"): the legacy gaps,
 * Required and Conditional pairs that aren't verified yet, committed as capability-baseline.json.
 * It may only shrink: a new gap fails the check (a new component or layout adopts what applies), and a
 * gap that has closed must be removed.
 *
 *   npm run design-capabilities                       checks the baseline (also run by npm run check)
 *   npm run design-capabilities -- --update-baseline  removes closed gaps; refuses to add new ones
 *   npm run design-capabilities -- --init-baseline    writes the first baseline; refuses if one exists
 *
 * Availability comes from the declarations, the schema markers and the registered evidence. Evidence
 * counts as passing here because the harness test in `npm run check` fails otherwise.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { createJiti } from 'jiti'
import { format, resolveConfig } from 'prettier'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
// `--baseline <file>` reads and writes another file; the tests use it.
const fileArg = process.argv.indexOf('--baseline')
const file = fileArg > -1 ? process.argv[fileArg + 1] : join(root, 'capability-baseline.json')
const jiti = createJiti(import.meta.url, {
  alias: { '@': join(root, 'src') },
  interopDefault: true,
  jsx: { runtime: 'automatic' },
})

const { DESIGN_COMPONENTS, gate } = await jiti.import(join(root, 'src/app/design-components.ts'))
const { EVIDENCE } = await jiti.import(join(root, 'src/lib/design/capability-evidence.ts'))
const { currentBaseline, ratchetProblems } = await jiti.import(
  join(root, 'src/lib/design/capability-availability.ts'),
)

const COMMENT =
  'Generated by `npm run design-capabilities -- --init-baseline`. Legacy design capability gaps (task 275): each pair a component should offer but does not yet verify, with the task that closes it. It only shrinks: run `-- --update-baseline` after closing a gap. Never add to it by hand.'

const current = currentBaseline(DESIGN_COMPONENTS, EVIDENCE, gate)
const ids = DESIGN_COMPONENTS.map((component) => component.id)
// Formatted as the repository formats JSON, so `npm run format:check` agrees with what is written.
const write = async (baseline) =>
  writeFileSync(
    file,
    await format(JSON.stringify({ $comment: COMMENT, ...baseline }), {
      ...(await resolveConfig(file)),
      filepath: file,
    }),
  )
const count = (baseline) =>
  `${baseline.required.length} required and ${baseline.conditional.length} conditional pairs`

if (process.argv.includes('--init-baseline')) {
  if (existsSync(file)) {
    console.error(
      'capability-baseline.json exists already. It only shrinks: use --update-baseline.',
    )
    process.exit(1)
  }
  await write(current)
  console.log(`Wrote capability-baseline.json: ${count(current)}.`)
  process.exit(0)
}

if (!existsSync(file)) {
  console.error('capability-baseline.json is missing. Write it once with --init-baseline.')
  process.exit(1)
}
const committed = JSON.parse(readFileSync(file, 'utf8'))
const problems = ratchetProblems(current, committed, ids)
const added = problems.filter((problem) => problem.message.includes("isn't in the baseline"))

if (process.argv.includes('--update-baseline')) {
  if (added.length > 0) {
    for (const problem of added) console.error(`✗ ${problem.message}\n  ${problem.fix}`)
    console.error('The baseline only shrinks, so nothing was written.')
    process.exit(1)
  }
  await write(current)
  console.log(`Updated capability-baseline.json: ${count(current)}.`)
  process.exit(0)
}

if (problems.length > 0) {
  for (const problem of problems) console.error(`✗ ${problem.message}\n  ${problem.fix}`)
  process.exit(1)
}
console.log(`The capability baseline is current: ${count(current)}.`)
